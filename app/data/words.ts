export const curatedWords: WordEntry[] = MOODS.flatMap((mood, moodIndex) =>
  seeds[mood].map(([word, definition, editorialNote], wordIndex) => ({
    id: `c-${moodIndex + 1}-${wordIndex + 1}`,
    word,
    partOfSpeech: /다$/.test(word) ? "형용사·동사" : "명사",
    definition,
    editorialNote,
    moods: [mood],
    creativeUses: [...creativeUsesByIndex[wordIndex % creativeUsesByIndex.length]],
    curated: true,
    source: "krdict",
  })),
);

const curatedByMood = MOODS.map((_, moodIndex) =>
  curatedWords.slice(moodIndex * seeds[MOODS[moodIndex]].length, (moodIndex + 1) * seeds[MOODS[moodIndex]].length),
);

export const balancedCuratedWords: WordEntry[] = Array.from(
  { length: Math.max(...curatedByMood.map((entries) => entries.length)) },
  (_, wordIndex) => curatedByMood.map((entries) => entries[wordIndex]).filter(Boolean),
).flat() as WordEntry[];

export const wordById = new Map(curatedWords.map((entry) => [entry.id, entry]));

export function getTodayWord(date = new Date()): WordEntry {
  const dateParts = new Intl.DateTimeFormat("ko-KR", {
    timeZone: "Asia/Seoul",
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  })
    .formatToParts(date)
    .reduce<Record<string, string>>((parts, part) => {
      parts[part.type] = part.value;
      return parts;
    }, {});
  const dayKey = Number(`${dateParts.year}${dateParts.month}${dateParts.day}`);
  return curatedWords[dayKey % curatedWords.length];
}
